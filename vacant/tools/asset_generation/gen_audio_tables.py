#!/usr/bin/env python3
"""Generate the GBC note-period table and the wave-channel timbres.

Pulse channels: f = 131072 / (2048 - x). The wave channel plays one octave
lower for the same register value, so the composer looks up note + 12 for it.
Table covers MIDI 36..119 (pulse range C2..B8).
"""
import math
import sys
from pathlib import Path

out = Path(sys.argv[1])
LO, HI = 36, 119
periods = []
for m in range(LO, HI + 1):
    f = 440.0 * 2 ** ((m - 69) / 12)
    periods.append(max(0, min(2047, round(2048 - 131072 / f))))


def wave(fn):
    s = [max(0, min(15, round(fn(i / 32.0)))) for i in range(32)]
    return [(s[i] << 4) | s[i + 1] for i in range(0, 32, 2)]


S = math.sin
P = math.pi
waves = [
    # SOFT: a pure, slightly rounded sine - the default drone
    ('SOFT', wave(lambda t: 7.5 + 7.2 * S(2 * P * t))),
    # WARM: three harmonics of a saw, low-pass feel
    ('WARM', wave(lambda t: 7.5 + 4.9 * (S(2 * P * t) + S(4 * P * t) / 2.3 + S(6 * P * t) / 4.5))),
    # HOLLOW: odd harmonics, clarinet-like and dark
    ('HOLLOW', wave(lambda t: 7.5 + 6.2 * (S(2 * P * t) + S(6 * P * t) / 3.2 + S(10 * P * t) / 7))),
    # GLASS: fundamental plus a bright octave-and-fifth partial
    ('GLASS', wave(lambda t: 7.5 + 5.0 * (S(2 * P * t) + 0.45 * S(6 * P * t + 0.7) + 0.25 * S(8 * P * t)))),
    # BUZZ: a soft-edged narrow pulse for the industrial quarter
    ('BUZZ', wave(lambda t: 7.5 + 7.0 * (1 if (t % 1) < 0.3 else -0.45) * (0.8 + 0.2 * math.cos(2 * P * t)))),
]
L = ['/* Generated by tools/asset_generation/gen_audio_tables.py - do not edit. */',
     f'#define NOTE_LO {LO}u', f'#define NOTE_HI {HI}u', f'#define WAVE_COUNT {len(waves)}u',
     'static const uint16_t note_period[] = {']
L += ['    ' + ', '.join(str(p) for p in periods[i:i + 12]) + ','
      for i in range(0, len(periods), 12)]
L += ['};', f'static const uint8_t wave_table[{len(waves)}][16] = {{']
for name, d in waves:
    L.append('    {' + ', '.join(f'0x{b:02X}' for b in d) + '}, /* ' + name + ' */')
L.append('};')
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text('\n'.join(L) + '\n')
