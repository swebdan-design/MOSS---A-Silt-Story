#!/usr/bin/env python3
"""MOSS album artwork, drawn in code (Pillow for PNG; SVG written directly).

One 200 x 200 pixel-art scene is the master. Every export is an integer
upscale of it (15x = 3000 px, 5x = 1000 px), so the PNGs and the SVG show
exactly the same pixels. Colours start from SILT's RGB555 identity
(NAVY, INK, WATER, MUTED, WHITE, GOLD, SAGE) and add a few late-summer
greens and an amber. Typography is the SILT 5x7 pixel alphabet.
"""
import math, random, sys, os
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

sys.path.insert(0, os.path.dirname(__file__))
from art_scenes import FONT

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'release/artwork'
SRC = ROOT / 'assets/artwork-source'
OUT.mkdir(parents=True, exist_ok=True)
SRC.mkdir(parents=True, exist_ok=True)


def c555(r, g, b):
    return (r * 8, g * 8, b * 8)


PAL = {
    'navy': c555(2, 3, 6), 'ink': c555(2, 5, 8), 'water': c555(2, 7, 9), 'grid': c555(3, 9, 11),
    'muted': c555(10, 15, 17), 'white': c555(27, 29, 26), 'gold': c555(28, 26, 17), 'sage': c555(14, 22, 17),
    # late summer additions for MOSS
    'dusk': (44, 52, 70), 'haze': (82, 92, 96), 'amber': (196, 150, 84), 'moss': (64, 96, 64),
    'deep': (30, 46, 38), 'fern': (98, 136, 88), 'bark': (22, 30, 30), 'cream': (232, 226, 196),
}
W = H = 200


class Pix:
    def __init__(self, w=W, h=H, fill='navy'):
        self.w, self.h = w, h
        self.p = [[fill] * w for _ in range(h)]

    def set(self, x, y, c):
        x, y = int(round(x)), int(round(y))
        if 0 <= x < self.w and 0 <= y < self.h:
            self.p[y][x] = c

    def rect(self, x, y, w, h, c):
        for yy in range(int(y), int(y + h)):
            for xx in range(int(x), int(x + w)):
                self.set(xx, yy, c)

    def ellipse(self, cx, cy, rx, ry, c):
        for y in range(int(cy - ry) - 1, int(cy + ry) + 2):
            for x in range(int(cx - rx) - 1, int(cx + rx) + 2):
                if ((x - cx) / rx) ** 2 + ((y - cy) / ry) ** 2 <= 1:
                    self.set(x, y, c)

    def ring(self, cx, cy, rx, ry, c, gap=None):
        n = int(2 * math.pi * max(rx, ry) * 1.6) + 8
        for i in range(n):
            a = 2 * math.pi * i / n
            if gap and gap[0] < a < gap[1]: continue
            self.set(cx + rx * math.cos(a), cy + ry * math.sin(a), c)

    def line(self, x0, y0, x1, y1, c):
        n = int(max(abs(x1 - x0), abs(y1 - y0))) + 1
        for i in range(n + 1):
            t = i / n
            self.set(x0 + (x1 - x0) * t, y0 + (y1 - y0) * t, c)

    def text(self, x, y, s, c, scale=1):
        for ch in s:
            g = FONT.get(ch)
            if ch == ' ' or g is None:
                x += 3 * scale; continue
            w = max([max([i + 1 for i, v in enumerate(r) if v == '#'] or [0]) for r in g] or [1])
            for ry, r in enumerate(g):
                for rx, v in enumerate(r):
                    if v == '#': self.rect(x + rx * scale, y + ry * scale, scale, scale, c)
            x += (w + 1) * scale

    def text_w(self, s, scale=1):
        w = 0
        for ch in s:
            g = FONT.get(ch)
            if ch == ' ' or g is None: w += 3 * scale; continue
            w += (max([max([i + 1 for i, v in enumerate(r) if v == '#'] or [0]) for r in g]) + 1) * scale
        return w - scale

    def ctext(self, y, s, c, scale=1, cx=None):
        cx = self.w // 2 if cx is None else cx
        self.text(cx - self.text_w(s, scale) // 2, y, s, c, scale)

    def image(self, scale):
        img = Image.new('RGB', (self.w, self.h))
        img.putdata([PAL[c] for row in self.p for c in row])
        return img.resize((self.w * scale, self.h * scale), Image.NEAREST)

    def svg(self, path, scale=15, title='MOSS'):
        parts = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{self.w * scale}" height="{self.h * scale}" '
                 f'viewBox="0 0 {self.w} {self.h}" shape-rendering="crispEdges">',
                 f'<title>{title}</title>',
                 '<!-- Generated by tools/create_artwork.py. Each rect is a run of identical pixels. -->']
        for y, row in enumerate(self.p):
            x = 0
            while x < self.w:
                c = row[x]; e = x + 1
                while e < self.w and row[e] == c: e += 1
                r, g, b = PAL[c]
                parts.append(f'<rect x="{x}" y="{y}" width="{e - x}" height="1" fill="#{r:02x}{g:02x}{b:02x}"/>')
                x = e
        parts.append('</svg>')
        Path(path).write_text('\n'.join(parts))


def scene(pix, ox=0, oy=0, wide=False):
    """Late-summer dusk: sky, moon, distant wood, meadow, willow, pond, boy."""
    w, h = pix.w, pix.h
    rnd = random.Random(1979)
    # sky bands with ordered dithering between them
    bands = [('navy', 0), ('ink', 46), ('dusk', 78), ('haze', 100)]
    bayer = [[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]
    for y in range(0, 118):
        for i in range(len(bands) - 1):
            if bands[i][1] <= y < bands[i + 1][1]:
                lo, hi = bands[i], bands[i + 1]; break
        else:
            lo = hi = bands[-1]
        t = (y - lo[1]) / max(1, hi[1] - lo[1])
        for x in range(w):
            pix.set(x, y, hi[0] if t * 16 > bayer[y % 4][x % 4] + 6 else lo[0])
    for _ in range(int(70 * w / 200)):
        x, y = rnd.randrange(w), rnd.randrange(80)
        pix.set(x, y, 'white' if rnd.random() < 0.3 else 'muted')
    # SILT's crescent moon
    mx = w - 34
    pix.ellipse(mx, 30, 9, 9, 'gold')
    pix.ellipse(mx + 4, 27, 8.5, 8.5, 'navy')
    # distant wood on the horizon
    for x in range(w):
        hgt = 10 + int(4 * math.sin(x / 9.0) + 3 * math.sin(x / 3.7 + 1) + 2 * math.sin(x / 1.7))
        pix.rect(x, 118 - hgt, 1, hgt, 'deep')
    # meadow
    pix.rect(0, 118, w, h - 118, 'moss')
    for y in range(118, h):
        for x in range(w):
            if (x * 7 + y * 13) % 23 == 0: pix.set(x, y, 'fern')
            elif (x * 5 + y * 11) % 37 == 0: pix.set(x, y, 'deep')
    # the pond: small, intimate, with SILT's two stones and widening circles
    px_, py_ = int(w * 0.62), 150
    pix.ellipse(px_, py_, 46, 15, 'deep')
    pix.ellipse(px_, py_, 44, 13, 'water')
    pix.ellipse(px_, py_ + 2, 40, 10, 'ink')
    for k, r in enumerate((8, 15, 23, 31)):
        pix.ring(px_ - 14, py_, r, r * 0.34, 'grid' if k < 2 else 'water')
    pix.ring(px_ + 16, py_, 7, 2.4, 'grid')
    pix.ring(px_ + 16, py_, 13, 4.5, 'water')
    for sx in (px_ - 14, px_ + 16):
        pix.ellipse(sx, py_, 4, 2, 'muted')
        pix.rect(sx - 2, py_ - 2, 4, 1, 'white')
    for lx, ly in ((px_ - 32, py_ - 4), (px_ + 30, py_ + 5), (px_ + 2, py_ - 7), (px_ - 4, py_ + 8)):
        pix.ellipse(lx, ly, 4, 1.6, 'sage')
        pix.set(lx + 2, ly, 'water')
    pix.set(px_ + 2, py_ - 9, 'gold'); pix.set(px_ + 2, py_ - 10, 'white')
    # moonlight on the water
    for i in range(6):
        pix.rect(px_ + 18 - i, py_ - 9 + i * 3, 6 - i % 3, 1, 'muted')
    # reeds at the far bank
    for x in range(px_ + 30, px_ + 46, 2):
        top = py_ - 16 - (x * 7) % 6
        pix.line(x, py_ - 6, x + 1, top, 'deep')
        pix.set(x + 1, top - 1, 'amber')
    # the boy's stone, left on the near bank
    pix.ellipse(px_ - 26, py_ + 21, 2.5, 1.5, 'muted'); pix.set(px_ - 27, py_ + 20, 'white')
    # the boy, sitting, seen from behind
    bx, by = px_ - 6, py_ + 26
    pix.ellipse(bx, by - 10, 3.5, 3.5, 'bark')
    pix.rect(bx - 4, by - 7, 9, 6, 'navy')
    pix.rect(bx - 5, by - 2, 11, 3, 'bark')
    pix.set(bx + 2, by - 12, 'haze')
    # the great willow, left
    tx = int(w * 0.2)
    pix.rect(tx - 5, 112, 10, 40, 'bark')
    pix.line(tx - 5, 150, tx - 12, 156, 'bark'); pix.line(tx + 4, 150, tx + 11, 156, 'bark')
    for dx in range(-3, 4):
        pix.line(tx + dx, 116, tx + dx * 5, 90, 'bark')
    pix.ellipse(tx, 88, 38, 18, 'deep')
    pix.ellipse(tx - 6, 84, 26, 11, 'moss')
    for i in range(70):
        sx = tx - 40 + i * 80 / 70 + rnd.uniform(-1, 1)
        top = 82 + abs(sx - tx) * 0.2 + rnd.uniform(-3, 3)
        length = 34 + rnd.uniform(0, 40) - abs(sx - tx) * 0.45
        c = rnd.choice(['deep', 'deep', 'moss', 'fern'])
        for k in range(int(length)):
            pix.set(sx + (sx - tx) * 0.004 * k + math.sin(k / 9 + i) * 0.6, top + k, c)
    for i in range(18):
        pix.set(tx - 30 + rnd.uniform(0, 60), 76 + rnd.uniform(0, 22), 'sage')
    # fireflies
    for _ in range(14):
        fx, fy = rnd.uniform(10, w - 10), rnd.uniform(100, 175)
        pix.set(fx, fy, 'gold')
    # grass tufts foreground
    for x in range(0, w, 3):
        hgt = 3 + (x * 13) % 7
        pix.line(x, h, x + (x % 2), h - hgt, 'deep')


def cover(text=True):
    pix = Pix()
    scene(pix)
    if text:
        pix.ctext(14, 'MOSS', 'cream', 5)
        pix.ctext(56, 'A SILT Story', 'muted', 1)
        pix.ctext(66, 'by Synth Centric', 'sage', 1)
    return pix


TRACKS = ['The Cottage', 'Whispering Wood', 'The Three Stones', 'Summer Rain', 'The Old Railway',
          'The Hill', 'The Pond at Evening', 'Before Leaving', 'The First Listener', 'The Pond Remains']


def back_cover():
    pix = Pix(fill='navy')
    for y in range(140, 200):
        for x in range(200):
            pix.set(x, y, 'ink' if (x + y) % 2 else 'navy')
    pix.ellipse(100, 172, 70, 14, 'water')
    pix.ellipse(100, 174, 66, 11, 'ink')
    for r in (8, 16, 26):
        pix.ring(76, 172, r, r * 0.33, 'grid')
    pix.ellipse(76, 172, 4, 2, 'muted'); pix.ellipse(124, 172, 4, 2, 'muted')
    pix.ellipse(100, 190, 2.5, 1.5, 'muted')
    pix.ctext(10, 'MOSS', 'cream', 2)
    pix.ctext(28, 'A SILT Story', 'muted')
    for i, t in enumerate(TRACKS):
        y = 44 + i * 9
        pix.text(40, y, f'{i + 1:02d}', 'gold')
        pix.text(56, y, t, 'white')
    pix.ctext(140, 'by Synth Centric', 'sage')
    return pix


def save_png(img, name):
    img.save(OUT / name, optimize=True)
    print('wrote', OUT / name, img.size)


def main():
    c = cover(True)
    save_png(c.image(15), 'MOSS_Cover_3000x3000.png')
    save_png(c.image(5), 'MOSS_Cover_1000x1000.png')
    c.svg(OUT / 'MOSS_Cover.svg', title='MOSS - A SILT Story - by Synth Centric')
    n = cover(False)
    save_png(n.image(15), 'MOSS_Cover_No_Text.png')
    n.svg(SRC / 'MOSS_Cover_No_Text.svg', title='MOSS (text-free)')
    b = back_cover()
    save_png(b.image(15), 'MOSS_Back_Cover.png')
    b.svg(SRC / 'MOSS_Back_Cover.svg', title='MOSS back cover')
    # promotional banner 3:1
    p = Pix(300, 100)
    big = Pix(300, 200)
    scene(big)
    for y in range(100):
        p.p[y] = big.p[y + 38][:]
    p.ctext(6, 'MOSS', 'cream', 4, cx=220)
    p.ctext(40, 'A SILT Story', 'muted', 1, cx=220)
    p.ctext(50, 'by Synth Centric', 'sage', 1, cx=220)
    p.ctext(88, 'for the original Game Boy', 'white', 1, cx=150)
    save_png(p.image(10), 'MOSS_Promo.png')
    p.svg(SRC / 'MOSS_Promo.svg', 10, 'MOSS promotional banner')
    # small social graphic, 1080 x 1080
    s = Image.new('RGB', (1080, 1080), PAL['navy'])
    s.paste(c.image(5), (40, 40))
    save_png(s, 'MOSS_Social_1080.png')
    # cartridge label mock-up
    lab = cover(True).image(2)
    cart = Image.new('RGB', (520, 600), (24, 26, 30))
    d = ImageDraw.Draw(cart)
    d.rounded_rectangle((20, 10, 500, 590), 26, fill=(170, 170, 176), outline=(110, 110, 116), width=4)
    d.rectangle((20, 10, 500, 40), fill=(150, 150, 156))
    for x in range(60, 470, 18): d.line((x, 18, x, 32), fill=(120, 120, 126), width=6)
    d.rectangle((58, 70, 462, 474), fill=(36, 40, 44))
    cart.paste(lab.resize((392, 392), Image.NEAREST), (64, 76))
    d.polygon([(470, 590), (500, 560), (500, 590)], fill=(24, 26, 30))
    try:
        f = ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf', 18)
        d.text((260, 520), 'MOSS  -  A SILT Story', fill=(60, 60, 66), font=f, anchor='mm')
    except OSError:
        pass
    save_png(cart, 'MOSS_Cartridge_Label_Mockup.png')


if __name__ == '__main__':
    main()
