#!/usr/bin/env python3
"""Generate the DMG period table and wave-channel patterns (stdlib only).

Pulse period x gives f = 131072 / (2048 - x). The wave channel uses the same
register value one octave lower, so callers add 12 to its MIDI note.
"""
import math, sys
from pathlib import Path

out = Path(sys.argv[1])
lo, hi = 36, 107
periods = []
for m in range(lo, hi + 1):
    f = 440.0 * 2 ** ((m - 69) / 12)
    periods.append(max(0, min(2047, round(2048 - 131072 / f))))

def wave(fn):
    s = [max(0, min(15, round(fn(i / 32.0)))) for i in range(32)]
    return [(s[i] << 4) | s[i + 1] for i in range(0, 32, 2)]

waves = {
    'SOFT':   wave(lambda t: 7.5 + 7.4 * math.sin(2 * math.pi * t)),
    # Odd harmonics, flattened peaks: a hollow, wooden flute.
    'HOLLOW': wave(lambda t: 7.5 + 7.4 * max(-1, min(1, 1.35 * (math.sin(2*math.pi*t) + math.sin(6*math.pi*t)/5)))),
    # Rounded saw: first three harmonics only.
    'WARM':   wave(lambda t: 7.5 + 5.2 * (math.sin(2*math.pi*t) + math.sin(4*math.pi*t)/2.2 + math.sin(6*math.pi*t)/4)),
    # Soft narrow pulse: a reed-like nasal colour.
    'REED':   wave(lambda t: 7.5 + 7.4 * (1 if (t % 1) < 0.28 else -0.55) * (0.75 + 0.25 * math.cos(2*math.pi*t))),
}
lines = ['/* Generated by tools/gen_audio_tables.py - do not edit. */',
         f'#define NOTE_LO {lo}', f'#define NOTE_HI {hi}',
         'static const uint16_t note_period[] = {']
lines += ['    ' + ', '.join(str(p) for p in periods[i:i+12]) + ',' for i in range(0, len(periods), 12)]
lines += ['};', 'static const uint8_t wave_table[4][16] = {']
for name, data in waves.items():
    lines.append('    {' + ', '.join(f'0x{b:02X}' for b in data) + '}, /* ' + name + ' */')
lines.append('};')
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text('\n'.join(lines) + '\n')
